def build_obj_abi_probe() -> bytes:
    main = Function("fn_objabi", INT)
    entry = main.entry
    seven = main.new_vreg(INT, "seven")
    boxed = main.new_vreg(INT, "boxed")
    obj = main.new_vreg(OBJ, "obj")
    returned = main.new_vreg(OBJ, "returned")
    value = main.new_vreg(INT, "value")
    cond = main.new_vreg(BOOL, "cond")
    zero = main.new_vreg(INT, "zero")
    one = main.new_vreg(INT, "one")
    ok = main.new_block("ok")
    bad = main.new_block("bad")
    entry.add("const", seven, 7)
    entry.add("call", boxed, "rt_box_int", (seven,))
    entry.add("mov", obj, boxed)
    entry.add("call", returned, "fn_objid", (obj,))
    entry.add("call", value, "rt_unbox_int", (returned,))
    entry.add("cmp", cond, "eq", value, seven)
    entry.add("br", None, cond, ok.label, bad.label)
    ok.add("call", None, "rt_decref", (returned,))
    ok.add("const", zero, 0)
    ok.add("ret", None, zero)
    bad.add("const", one, 1)
    bad.add("ret", None, one)

    ident = Function("fn_objid", OBJ)
    p = ident.new_vreg(OBJ, "p")
    ident.params = [p]
    ident.entry.add("arg", p, 0)
    ident.entry.add("ret", None, p)

    program = Program(functions=[main, ident], main=main)
    rdata = DataBuilder()
    data = DataBuilder()
    imports = make_imports()
    runtime = Runtime(imports, rdata, data)
    asm = Asm()
    runtime.emit(asm)
    allocs = {fn.name: allocate(fn) for fn in program.functions}
    emit_program(asm, program.functions, allocs, runtime, itertools.count())
    asm.bind("_start")
    asm.and_rsp(-16)
    asm.sub_rsp(32)
    asm.call(runtime.RT_INIT)
    asm.call(main.name)
    asm.mov_ri("rcx", 0)
    asm.call_iat(("idata", imports.slot("kernel32.dll", "ExitProcess")))
    rdata_bytes = bytes(rdata.buf)
    data_bytes = bytes(data.buf)
    lay = layout_image(bytes(asm.b), rdata_bytes, data_bytes, imports)
    asm.resolve(IMAGE_BASE, lay.rvas)
    return build_exe(bytes(asm.b), rdata_bytes, data_bytes, imports,
                     entry_off=asm.labels["_start"])


