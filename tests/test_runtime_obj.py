def build_object_probe() -> bytes:
    fn = Function("fn_objprobe", INT)
    entry = fn.entry
    size = fn.new_vreg(INT, "size")
    ptr = fn.new_vreg(INT, "ptr")
    rc = fn.new_vreg(INT, "rc")
    boxed = fn.new_vreg(INT, "boxed")
    value = fn.new_vreg(INT, "value")
    forty_two = fn.new_vreg(INT, "forty_two")
    value_ok = fn.new_vreg(BOOL, "value_ok")
    live = fn.new_vreg(INT, "live")
    live_ok = fn.new_vreg(BOOL, "live_ok")
    zero_live = fn.new_vreg(INT, "zero_live")
    kind = fn.new_vreg(INT, "kind")
    one_kind = fn.new_vreg(INT, "one_kind")
    kind_ok = fn.new_vreg(BOOL, "kind_ok")
    truth = fn.new_vreg(INT, "truth")
    one_truth = fn.new_vreg(INT, "one_truth")
    truth_ok = fn.new_vreg(BOOL, "truth_ok")
    two = fn.new_vreg(INT, "two")
    cond = fn.new_vreg(BOOL, "cond")
    zero = fn.new_vreg(INT, "zero")
    one = fn.new_vreg(INT, "one")

    ok = fn.new_block("ok")
    bad = fn.new_block("bad")
    value_ok_blk = fn.new_block("value_ok")
    type_ok = fn.new_block("type_ok")
    gc_ok = fn.new_block("gc_ok")
    fin = fn.new_block("fin")

    entry.add("const", size, 48)
    entry.add("call", ptr, "rt_alloc", (size,))
    entry.add("const", forty_two, 42)
    entry.add("call", boxed, "rt_box_int", (forty_two,))
    entry.add("call", None, "rt_print_obj", (boxed,))
    entry.add("call", truth, "rt_is_true", (boxed,))
    entry.add("const", one_truth, 1)
    entry.add("cmp", truth_ok, "eq", truth, one_truth)
    entry.add("br", None, truth_ok, value_ok_blk.label, bad.label)
    value_ok_blk.add("call", value, "rt_unbox_int", (boxed,))
    value_ok_blk.add("cmp", value_ok, "eq", value, forty_two)
    value_ok_blk.add("br", None, value_ok, type_ok.label, bad.label)

    type_ok.add("call", kind, "rt_typeof", (boxed,))
    type_ok.add("const", one_kind, 1)
    type_ok.add("cmp", kind_ok, "eq", kind, one_kind)
    type_ok.add("br", None, kind_ok, gc_ok.label, bad.label)

    gc_ok.add("call", None, "rt_gc_push_root", (ptr,))
    gc_ok.add("call", None, "rt_gc_collect", ())
    gc_ok.add("call", None, "rt_gc_pop_root", ())
    gc_ok.add("call", None, "rt_incref", (ptr,))
    gc_ok.add("call", rc, "rt_refcount", (ptr,))
    gc_ok.add("const", two, 2)
    gc_ok.add("cmp", cond, "eq", rc, two)
    gc_ok.add("br", None, cond, ok.label, bad.label)

    ok.add("call", None, "rt_decref", (ptr,))
    ok.add("call", None, "rt_decref", (ptr,))
    ok.add("call", live, "rt_gc_live", ())
    ok.add("const", zero_live, 0)
    ok.add("cmp", live_ok, "eq", live, zero_live)
    ok.add("br", None, live_ok, fin.label, bad.label)

    fin.add("const", zero, 0)
    fin.add("ret", None, zero)

    bad.add("const", one, 1)
    bad.add("ret", None, one)

    program = Program(functions=[fn], main=fn)
    rdata = DataBuilder()
    data = DataBuilder()
    imports = make_imports()
    runtime = Runtime(imports, rdata, data)
    asm = Asm()
    runtime.emit(asm)
    allocs = {fn.name: allocate(fn)}
    emit_program(asm, program.functions, allocs, runtime, itertools.count())

    asm.bind("_start")
    asm.and_rsp(-16)
    asm.sub_rsp(32)
    asm.call(runtime.RT_INIT)
    asm.call(fn.name)
    asm.mov_ri("rcx", 0)
    asm.call_iat(("idata", imports.slot("kernel32.dll", "ExitProcess")))

    rdata_bytes = bytes(rdata.buf)
    data_bytes = bytes(data.buf)
    lay = layout_image(bytes(asm.b), rdata_bytes, data_bytes, imports)
    asm.resolve(IMAGE_BASE, lay.rvas)
    return build_exe(bytes(asm.b), rdata_bytes, data_bytes, imports,
                     entry_off=asm.labels["_start"])


