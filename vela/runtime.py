    def _emit_fail(self, a: Asm) -> None:
        a.bind(self.FAIL)
        # Entered via jmp from arbitrary stack alignment: normalize before
        # building the frame so the WriteFile call below is ABI-correct.
        a.and_rsp(-16)
        a.sub_rsp(8)
        a.push_r("rbp")
        a.mov_rr("rbp", "rsp")
        a.sub_rsp(64)
        a.mov_rr("r10", "rcx")
        a.add_ri("r10", 8)
        a.mov_rm("r8", "rcx", 0)
        self._load_handle(a, "rcx", err=True)
        a.mov_rr("rdx", "r10")
        a.lea("r9", "rbp", -8)
        a.mov_mi("rsp", 32, 0)
        self._call(a, KERNEL32, "WriteFile")
        a.mov_ri("rcx", 1)
        self._call(a, KERNEL32, "ExitProcess")
        a.bind("rt_fail_hang")
        a.jmp("rt_fail_hang")

    def _emit_stubs(self, a: Asm) -> None:
        a.bind(self.OVERFLOW)
        self._fail(a, self.msg_overflow)
        a.bind(self.RANGE_ERROR)
        self._fail(a, self.msg_stepzero)
